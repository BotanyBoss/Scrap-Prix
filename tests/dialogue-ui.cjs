/* UI-only dialogue prototype regression tests. */
(function testDialogue(){
  const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
  const html=fs.readFileSync(path.join(__dirname,'..','dist','dev.html'),'utf8');
  const scripts=[...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)].map(x=>x[1]);
  assert.equal(scripts.length,30);
  const ctx=vm.createContext({console});ctx.window=ctx;ctx.globalThis=ctx;
  vm.runInContext(scripts[27],ctx);
  const UI=ctx.ScrapDialogueUI;
  assert(UI&&typeof UI.garage==='function'&&typeof UI.race==='function');
  assert.equal(UI.garage('start').speaker,'GARAGE / TEST');
  assert.equal(UI.garage('bodge').channel,'EMERGENCY BODGE');
  assert.equal(UI.garage('made-up'),null);
  const start=UI.race({step:{id:'opening'}});
  assert(start&&start.speaker==='RADIO / TEST');
  const anomaly=UI.race({step:{id:'x',sourceKind:'anomaly',sourceId:'kaiju-crossing'}});
  assert.equal(anomaly.channel,'UNUSUAL EVENT');
  const hazard=UI.race({step:{id:'x',sourceKind:'signature',sourceId:'crosswind'}});
  assert.equal(hazard.channel,'TRACK HAZARD');
  const pass=UI.race({step:{id:'some-step'},special:{id:'spring-trap'}});
  assert.equal(pass.speaker,'RIVAL / TEST');
  assert.equal(pass.id,'pass:spring-trap');
  assert.equal(UI.race({step:{id:'some-step'},fake:{id:'goose'}}).channel,'RIVAL RADIO');
  assert.equal(UI.race({step:{id:'opening'},choice:true}),null,'Route choice suppresses chatter');
  assert.equal(UI.race({step:{id:'opening'},cinematic:true}),null,'Transformation movie suppresses chatter');
  assert.equal(UI.race({step:{id:'lap-2'}}),null,'No panel when there is no relevant cue');
  assert.equal(UI.race({step:{id:'finish'}}).channel,'FINISH');
  const htmlVisible=UI.markup(UI.garage('return'),'garage');
  assert(htmlVisible.includes('id="garage-dialogue"'));
  assert(htmlVisible.includes('data-action="dismiss-dialogue"'));
  assert(htmlVisible.includes('NO VOICE'));
  assert(UI.markup(null,'race').includes('hidden'));
  assert(!UI.markup({...UI.garage('start'),text:'<script>window.bad=true</script>'},'garage').includes('<script>'),'Dialogue must escape HTML');
  let stub={dataset:{},hidden:true,innerHTML:''};
  ctx.document={getElementById:id=>id==='race-dialogue'?stub:null};
  UI.update('race-dialogue',start);
  assert(!stub.hidden&&stub.innerHTML.includes('RADIO / TEST'));
  const inner=stub.innerHTML;
  UI.update('race-dialogue',start);
  assert.equal(stub.innerHTML,inner,'Same cue must not redraw each frame');
  UI.update('race-dialogue',null);
  assert(stub.hidden&&stub.innerHTML==='');
  console.log('PASS: anonymous dialogue roles, context cues, cinematic/choice priority, safe markup, dismissal-ready panels and stable updates.');
})();
