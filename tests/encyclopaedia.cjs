/* Scrap Prix Encyclopaedia regression tests. */
(function(){
  const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
  const html=fs.readFileSync(path.join(__dirname,'..','dist','dev.html'),'utf8');
  const scripts=[...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)].map(m=>m[1]);
  assert.equal(scripts.length,30);
  const saved=new Map(),storage={getItem:k=>saved.get(k)||null,setItem:(k,v)=>saved.set(k,String(v))};
  const load=()=>{
    const ctx=vm.createContext({console,localStorage:storage});
    ctx.window=ctx;ctx.globalThis=ctx;
    for(const i of [0,1,2,3,25,26])vm.runInContext(scripts[i],ctx);
    return ctx;
  };
  const ctx=load(),D=ctx.ScrapData,E=ctx.ScrapEngine,A=ctx.ScrapEncyclopaedia;
  const snap=()=>JSON.parse(JSON.stringify(A.snapshot()));
  assert.deepEqual(Array.from(A.tabs()),['events','weather','shortcuts','tracks','parts','bounties']);
  for(const tab of A.tabs())assert.equal(A.list(tab).length,0,'Do not prefill '+tab);
  const rare=D.ANOMALIES.find(x=>x.id==='kaiju-crossing');
  A.recordEventMissed('anomaly',rare.id);
  assert.equal(A.list('events')[0].name,'?');
  assert.equal(A.list('events')[0].group,'Legendary');
  A.recordEventSeen('anomaly',rare.id);
  assert.equal(A.list('events')[0].name,rare.title);
  A.recordEventMissed('anomaly',rare.id);
  assert.equal(A.list('events')[0].name,rare.title,'Witnessing is permanent');
  const short=D.WILDCARDS.find(x=>x.id==='wreckage-shortcut');
  assert(short);
  A.recordEventMissed('wildcard',short.id);
  assert.equal(A.list('shortcuts')[0].name,'?');
  A.recordEventSeen('wildcard',short.id);
  assert.equal(A.list('shortcuts')[0].name,short.title);
  assert.equal(A.list('events').length,1,'Shortcut is categorised separately');
  A.recordTrack(D.TRACKS[0].id,false);
  assert.equal(A.list('tracks')[0].name,'?');
  A.recordTrack(D.TRACKS[0].id,true);
  assert.equal(A.list('tracks')[0].name,D.TRACKS[0].name);
  A.recordTrack(D.TRACKS[0].id,false);
  assert.equal(A.list('tracks')[0].name,D.TRACKS[0].name);
  const weather=D.WEATHER.find(x=>x.id==='blizzard');A.recordWeather(weather.id);
  assert.equal(A.list('weather')[0].name,weather.name);
  const part=D.PARTS.find(x=>x.price>0);
  A.recordPartSpotted(part.id);
  assert.equal(A.list('parts')[0].state,'spotted');
  assert.equal(A.list('parts')[0].name,'?');
  A.recordPartEquipped(part.id,4);
  assert.equal(A.list('parts')[0].name,part.name);
  A.startRun();A.recordPartTuned(part.id,5);A.recordPartTuned(part.id,6);
  assert.equal(A.list('parts')[0].mostTunes,2);
  A.startRun();A.recordPartTuned(part.id,7);
  assert.equal(A.list('parts')[0].mostTunes,2);
  assert.equal(A.list('parts')[0].level,7);
  const bounty=E.bountyDefinitions.find(x=>x.id==='phoenix');
  A.recordBountyOffered(bounty.id);
  assert.equal(A.list('bounties')[0].name,'?');
  A.recordBountyCompleted(bounty.id);A.recordBountyCompleted(bounty.id);
  assert.equal(A.list('bounties')[0].count,2);
  assert.equal(A.list('bounties')[0].name,bounty.title);
  const run=JSON.parse(JSON.stringify(E.newRun(84)));
  assert.equal(E.bountyDisplay(run,{id:'tank'}).revealed,false);
  A.recordGag('tank');
  assert.equal(A.tabs().includes('gags'),true,'Gag tab appears on first build');
  assert.equal(A.list('gags').length,1,'Remaining gags stay absent');
  assert.equal(E.bountyDisplay(run,{id:'tank'}).revealed,true,'Decode from permanent Encyclopaedia');
  A.startRun();
  assert.equal(A.list('gags').length,1,'Discovery survives new runs');
  assert.equal(A.list('bounties')[0].count,2);
  const record={race:1,trackId:D.TRACKS[1].id,place:2,noStart:false,failedSlot:null,gagId:null,
    bountyResults:[{id:bounty.id,success:true}]};
  A.recordResult(record);A.recordResult(record);
  assert.equal(A.list('bounties')[0].count,3,'Race settlement recorded once only');
  assert.equal(A.list('tracks').find(x=>x.key===record.trackId).name,'?');
  assert.equal('encyclopaedia' in E.validateSave(run),false,'Not coupled to run saves');
  assert(saved.has(A.KEY));
  const sessionId=snap().session.id;
  const again=load().ScrapEncyclopaedia;
  assert.equal(again.isGagKnown('tank'),true,'Persistent across page reload');
  assert.equal(again.list('bounties')[0].count,3);
  assert.equal(again.snapshot().session.id,sessionId);
  console.log('PASS: organic unknowns, witnessed-only events, win-to-unlock tracks, shop silhouettes, highest level/tunes, bounty counts, secret gag tab and lifetime persistence.');
})();
