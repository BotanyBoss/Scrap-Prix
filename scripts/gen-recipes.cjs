// Generates docs/GAG-RECIPES.md from the built game's catalogue, so the list cannot go stale.
//   node scripts/gen-recipes.cjs           write the doc
//   node scripts/gen-recipes.cjs --check   fail if the doc is out of date
const fs=require('fs'),path=require('path'),vm=require('vm');
const root=path.resolve(__dirname,'..'),out=path.join(root,'docs/GAG-RECIPES.md');
const html=fs.readFileSync(path.join(root,'dist/dev.html'),'utf8');
const scripts=[...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)].map(m=>m[1]);
const ctx=vm.createContext({console});ctx.globalThis=ctx;ctx.window=ctx;
for(const i of [0,1,2,3])vm.runInContext(scripts[i],ctx);
const D=ctx.ScrapData,SLOTS=['chassis','engine','tyres','gadget'];

const pct=v=>Math.round(v*1000)/10+'%';
const LABELS={obstacleDamageReduction:'obstacle damage',obstacleMomentumReduction:'obstacle momentum loss',straightPowerBonus:'power on straights',massAccelerationReduction:'weight acceleration penalty',roughMomentumReduction:'rough-surface momentum loss',dryStraightPowerBonus:'power on dry straights',smoothTyreWearReduction:'tyre wear on smooth surfaces',heatReduction:'heat',softPenaltyReduction:'soft-surface penalty',sandPenaltyReduction:'sand penalty',sandGripBonus:'grip on sand',snowPenaltyReduction:'snow penalty',winterGripBonus:'winter grip',extraWindReduction:'wind effects',impactWearReduction:'impact wear',engineHeatWearReduction:'engine heat wear',rocketGripPenaltyReduction:'rocket grip penalty'};
function perk(e){
  return Object.entries(e).filter(([k])=>k!=='name').map(([k,v])=>{
    if(k==='coolingToPowerCap')return `converts cooling to power (cap ${v})`;
    const label=LABELS[k]||k,bonus=/Bonus$/.test(k);
    return bonus?`+${pct(v)} ${label}`:`-${pct(v)} ${label}`;
  }).join(', ');
}

const lines=['# Gag vehicle recipes','',
'> Generated by `node scripts/gen-recipes.cjs` from `src/02-catalogue.js`. Do not edit by hand; `tests/check.cjs` fails if this file is out of date.','',
`${D.GAG_RECIPES.length} exact four-part combinations. All four parts must match exactly.`,'',
'| Vehicle | Chassis | Engine | Tyres | Gadget | Perk |','| --- | --- | --- | --- | --- | --- |'];
for(const r of D.GAG_RECIPES){
  const names=SLOTS.map(s=>{const p=D.PARTS.find(x=>x.id===r.requires[s]&&x.slot===s);if(!p)throw new Error(`Recipe ${r.id} references unknown ${s} part ${r.requires[s]}`);return p.name;});
  const e=D.GAG_EFFECTS[r.id];if(!e)throw new Error(`Recipe ${r.id} has no GAG_EFFECTS entry`);
  lines.push(`| ${r.name} | ${names.join(' | ')} | **${e.name}**: ${perk(e)} |`);
}
const text=lines.join('\n')+'\n';

if(process.argv.includes('--check')){
  const current=fs.existsSync(out)?fs.readFileSync(out,'utf8'):'';
  if(current.replace(/\r\n/g,'\n')!==text){console.error('FAIL: docs/GAG-RECIPES.md is out of date. Run: node scripts/gen-recipes.cjs');process.exit(1);}
  console.log('PASS: docs/GAG-RECIPES.md matches the catalogue.');
}else{fs.writeFileSync(out,text);console.log('Wrote docs/GAG-RECIPES.md');}
